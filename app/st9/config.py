"""Конфигурация ST9 — «трендовая корзина» (Donchian-пробой + ATR-трейлинг, 60м бары).

ЧЕСТНАЯ РАМКА (итог поиска 08.07, длинная история 7.5 лет): НИ ОДИН трендер соло не
проходит строгий гейт (все годы+) — золото оказалось артефактом окна 2023-26. Ценность
только в КОРЗИНЕ независимых слабых трендеров (механика AHL/Winton). Это НАПРАВЛЕННАЯ
ставка с плечом, не market-neutral.

ПОТОЛОК ДОХОДНОСТИ (ревизия 30.07 на ЧЕСТНОЙ комиссии 0.05% нотионала — замер по
счёту, 292 сделки; просадка mark-to-market, ГО перпов ≈15% нотионала): при текущем
плече (go_target_pct=15) 3 оси дают ~17%/год при DD ~5-6% капитала.
История оценок: 30-50% (первичная) → ~28% (25.07, комиссия ещё фиктивные 2 ₽/лот)
→ ~17% (30.07, комиссия фактическая). Каждое уточнение издержек СНИЖАЛО оценку —
относиться к любой новой цифре как к верхней границе, пока не проверена на счёте.
Выше 400к нотионала/ось заходить НЕЛЬЗЯ:
на 600к ГО в стрессе (биржа поднимает ставки вдвое в волатильность, ровно когда мы в
просадке) достигает 130% капитала = принудительное закрытие на дне. 100%+/год требуют
ГО ~99% капитала — маржин-колл арифметически гарантирован, это не стратегия.
Трейл НЕ защищает от гэпа: между барами исполнения нет.

Оси (60м перпы без роллов) — параметры после свипа 25.07:
- Si (USDRUBF, FX-девальвация): Donchian 70/10, ATR×5.0 — PF 2.29, 164 сд/3.5г
- GOLD (GLDRUBF, мировое золото): Donchian 45/16, ATR×5.0 — PF 1.76, 183 сд
- IMOEX (IMOEXF, РФ-акции): Donchian 45/35, ATR×6.0 — соло слаб, но corr к
  остальным ≈0 → работает диверсификатором (окно выхода 25→35 на ревизии 30.07)
v2: + GAZR (дневки 7 лет +25%/год) и BR (нефть).
НЕ добавлять CNYRUBF/EURRUBF: corr к USDRUBF 0.91/0.84 — та же ставка на рубль,
это увеличение плеча под видом диверсификации.
Граница частоты: удержание ≥1.5-2 дня = edge жив; быстрые окна = смерть band-стилем.
"""
from __future__ import annotations

from pydantic import BaseModel


class St9InstrumentCfg(BaseModel):
    secid: str                        # перпетуал FORTS (USDRUBF/GLDRUBF) ИЛИ ASSETCODE
    don_enter: int = 20               # окно пробоя входа (баров)
    don_exit: int = 10                # окно противопробоя выхода
    atr_mult: float = 3.0             # ATR(14)-трейлинг множитель
    entry_notional_rub: float = 100_000.0   # нотионал позиции на инструмент
    # квартальники: secid = ASSETCODE (GAZR), контракт резолвится динамически + ролл
    quarterly: bool = False
    roll_days_before: int = 3         # ролл за N дней до экспирации
    interval_min: int = 60            # ТФ баров: 60 (час) | 1440 (день; ISS interval=24)


class St9StrategyConfig(BaseModel):
    atr_period: int = 14
    allow_short: bool = True          # тренд двусторонний (шорт Si = укрепление рубля)
    # КОМИССИЯ — ДОЛЯ НОТИОНАЛА, не ₽/лот (замер по счёту 30.07: 0.05000% ровно на всех
    # трёх осях, 292 сделки). Прежняя модель 2 ₽/лот занижала издержки в 2.5× (GLDRUBF),
    # 5.5× (IMOEXF) и 19.6× (USDRUBF) — пропорциональность цене она не воспроизводила
    # в принципе. Нотионал лота = px × pv (pv=STEPPRICE/MINSTEP совпал с basicAssetSize
    # у всех осей, брокер считает от него же). Тот же тариф, что у st5 в песочнице.
    fee_pct_notional: float = 0.05    # % нотионала за сторону
    fee_per_lot: float = 0.0          # ₽/лот/сторона: доплата поверх %, 0 = только %
    daily_loss_limit_rub: float = 0.0
    # боевой лимит объёма: потолок нотионала одной позиции в tbank_real (пилот на малом
    # размере); сайзинг режется до лимита независимо от entry_notional_rub оси. 0 = без лимита.
    real_max_notional_rub: float = 100_000.0
    # ── УТИЛИЗАЦИЯ КАПИТАЛА / ПЛЕЧО (решение оператора 15.07: ГО до 15% = плечо ~3×) ──
    # go_target_pct: целевое ГО как % капитала счёта, делится на число ОТКРЫВАЕМЫХ осей.
    # Сайзинг: нотионал_оси = (капитал × go_target_pct/100 / N_осей) / go_frac, где go_frac
    # ≈ ГО/нотионал (≈0.044 для перпов). 0 = ВЫКЛ (старый режим по entry_notional_rub оси).
    # ⚠️ ПЛЕЧО масштабирует доходность И просадку. Направленная ставка — включать осознанно.
    go_target_pct: float = 0.0
    go_frac: float = 0.044            # доля ГО от нотионала (наблюдаемая для RUBF-перпов)
    # ПРЕДОХРАНИТЕЛЬ: стоп на просадку КАПИТАЛА от пика. При capital < peak×(1−pct/100) —
    # авто-flat всех осей + блок входов (guard срабатывает в live-цикле). 0 = выкл.
    # Обязателен при плече: трейл каждой позы не защищает от хвостового разворота портфеля.
    capital_dd_stop_pct: float = 0.0


class St9Config(BaseModel):
    strategy: St9StrategyConfig = St9StrategyConfig()
    instruments: list[St9InstrumentCfg] = [
        # Параметры пересмотрены 25.07 (свип на 3.5г истории + OOS 2023-24 → 2025-26,
        # с проскальзыванием 2 тика): длинное окно входа + свободный трейл. Прежние
        # 20/10/×3.0 и 32/16/×3.0 переторговывали (344 и 256 сделок) и пилились.
        # USDRUBF: PF 1.63→2.29, просадка 10388→5190₽, сделок 344→164.
        St9InstrumentCfg(secid="USDRUBF", don_enter=70, don_exit=10, atr_mult=5.0),
        # GLDRUBF: PF 1.32→1.76, просадка 1365→1068₽; 2025 из минуса (−689→+342).
        St9InstrumentCfg(secid="GLDRUBF", don_enter=45, don_exit=16, atr_mult=5.0),
        # ТРЕТЬЯ ОСЬ (25.07): IMOEXF — единственный НЕЗАВИСИМЫЙ диверсификатор.
        # corr часовых доходностей к USDRUBF/GLDRUBF ≈ −0.08…−0.02, тогда как валютные
        # перпы (CNYRUBF 0.91, EURRUBF 0.84) — та же ставка на рубль и НЕ диверсификаторы.
        # Ось слабая соло, но corr к остальным ≈0 → работает как диверсификатор.
        # pv=10 берётся с ISS автоматически (НЕ 1 — влияет на сайзинг в 10×).
        # Окно выхода 25→35 (30.07, после перехода на ЧЕСТНУЮ комиссию 0.05% нотионала):
        # 45/25 OOS НЕ устоял (PF 1.27), 45/35 держит 1.47 при OOS net 8430 против 4945.
        # Плато широкое и гладкое (вход 35-55, выход 30-45) — не изолированный пик.
        # 2023 убыточен у ВСЕХ вариантов оси одинаково (свойство года, не параметров).
        St9InstrumentCfg(secid="IMOEXF", don_enter=45, don_exit=35, atr_mult=6.0),
        # ЧЕТВЁРТАЯ ОСЬ (v2): РФ-акции — GAZR квартальники, ДНЕВНОЙ Donchian 20/10.
        # Единственный трендер, живой на ПОЛНОЙ истории 7 лет: +25%/год PF 2.01,
        # держит ex-2022 (+22.9%), corr к золоту +0.03 (независим). Ролл за 3 дня.
        St9InstrumentCfg(secid="GAZR", don_enter=20, don_exit=10, quarterly=True,
                         interval_min=1440, entry_notional_rub=100_000.0),
    ]
    # paper | tbank_sandbox | tbank_real. Установка tbank_real ордера НЕ шлёт: гейт
    # НА УРОВНЕ ОРДЕРА двойной — mode==tbank_real И real_trading_armed (+cooldown 600с
    # после старта live; взвод сбрасывается рестартом/сменой режима).
    mode: str = "paper"
    account_id: str = ""
    poll_seconds: float = 600.0       # 60м бары — опрос раз в 10 мин достаточно
    trading_enabled: bool = True
